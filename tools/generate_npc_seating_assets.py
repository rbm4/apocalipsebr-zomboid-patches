"""Generate/check stock 42.22.2 seating asset fingerprints and verify motion provenance.

Only hashes and measured root displacements are used; no game assets are copied.
"""
from pathlib import Path
import argparse
import hashlib
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "42.22.2/src/zombie/apocalipse/humans/seating/StockSeatingAssets.java"


def generate(media):
    def inherited(path, field, depth=0):
        assert depth < 8, "Animation inheritance too deep"
        node = ET.parse(path).getroot()
        value = node.findtext(field)
        parent = node.get("x_extends")
        return value if value is not None else inherited(path.parent / parent, field, depth + 1) if parent else None

    xmls = sorted((media / "AnimSets/player/sitonfurniture").rglob("*.xml"))
    xmls += sorted((media / "AnimSets/player/getup/fromSitOnFurniture").rglob("*.xml"))
    xmls += sorted((media / "AnimSets/player/getup/fromSitOnFurniture-Quick").rglob("*.xml"))
    assert xmls, "Missing native seating animation nodes"
    clips = {p.stem.lower(): p for p in (media / "anims_X/Bob").glob("*.x")}
    assets = set(xmls) | set((media / "AnimSets/player/getup").rglob("*.xml"))
    for directory in ("actiongroups/player/sitonfurniture", "actiongroups/player/getup"):
        assets.update((media / directory).rglob("*.xml"))
    for state in ("idle", "movement", "strafe"):
        assets.add(media / f"actiongroups/player/{state}/to_sitonfurniture.xml")
    def parents(path, depth=0):
        assert depth < 8
        parent = ET.parse(path).getroot().get("x_extends")
        if parent:
            target = (path.parent / parent).resolve()
            assets.add(target)
            parents(target, depth + 1)
    for path in list(assets):
        parents(path)
    motions = 0
    for xml in xmls:
        name = inherited(xml, "m_AnimName")
        path = clips[name.lower()]
        assets.add(path)
        if name.lower().startswith(("bob_seated_sitdown", "bob_seated_standup")):
            assert inherited(xml, "m_DeferredBoneName") == "Bip01"
            assert inherited(xml, "m_deferredBoneAxis") == "Z"
            data = path.read_text()
            block = re.search(r"Animation\s*\{\s*\{\s*Bip01\s*\}.*?AnimationKey T\s*\{(.*?)\}", data, re.S).group(1)
            frames = re.findall(r"(\d+);3;([^;]+)", block)
            first = list(map(float, frames[0][1].split(",")))
            last = list(map(float, frames[-1][1].split(",")))
            delta = tuple(round(last[i] - first[i], 6) for i in range(2))
            lower = name.lower()
            if "sitdown" in lower:
                expected = (-.003, .287944) if "sitdown_l" in lower or "sitdown_r_" in lower or lower.endswith("sitdown_r") else (-.003, -.263279)
                # Rifle is a front variant, not the right-side suffix.
                if "sitdown_rifle" in lower:
                    expected = (-.003, -.263279)
            elif "standup_l" in lower:
                expected = (.287795, -.00315)
            elif "standup_r_" in lower or lower.endswith("standup_r"):
                expected = (-.287795, .00315)
            else:
                expected = (.003, .286901)
            assert delta == expected, f"Unsupported root motion: {path.name}: {delta}"
            ticks = int(re.search(r"AnimTicksPerSecond\s*\{\s*(\d+)", data).group(1))
            assert int(frames[-1][0]) == ticks, f"Unsupported duration: {path}"
            motions += 1
    entries = []
    total = 0
    for path in sorted(assets):
        content = path.read_bytes()
        total += len(content)
        relative = "media/" + path.relative_to(media).as_posix()
        entries.append('        Map.entry("' + relative + '", "' + hashlib.sha256(content).hexdigest() + '")')
    assert len(assets) <= 256 and total <= 16 * 1024 * 1024
    source = '''// Generated by tools/generate_npc_seating_assets.py from target 42.22.2 assets.
package zombie.apocalipse.humans.seating;

import java.util.*;
import java.security.MessageDigest;

/** Fingerprints only; no game assets. Verification is bounded and performed once per capability bootstrap. */
public final class StockSeatingAssets {
    private StockSeatingAssets() { }
    public interface Reader { byte[] read(String relative) throws Exception; }
    public static final List<String> INVENTORIES=List.of("media/AnimSets/player/sitonfurniture", "media/AnimSets/player/getup", "media/actiongroups/player/sitonfurniture", "media/actiongroups/player/getup");
    public static final Map<String,String> HASHES=Map.ofEntries(
''' + ",\n".join(entries) + ''');
    public static boolean inventorySupported(Set<String> files){
        var expected=new HashSet<String>();
        for(String key:HASHES.keySet())if(key.endsWith(".xml")&&INVENTORIES.stream().anyMatch(p->key.startsWith(p+"/")))expected.add(key.toLowerCase(Locale.ROOT));
        return expected.equals(files);
    }
    public static boolean supported(Reader reader){
        try{
            long total=0;var digest=MessageDigest.getInstance("SHA-256");
            for(var asset:HASHES.entrySet()){
                var bytes=reader.read(asset.getKey());
                if(bytes==null||bytes.length>2*1024*1024||(total+=bytes.length)>16*1024*1024)return false;
                if(!HexFormat.of().formatHex(digest.digest(bytes)).equals(asset.getValue()))return false;
            }
            return true;
        }catch(Exception unsupported){return false;}
    }
}
'''
    return source, len(assets), total, motions


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--media", type=Path, default=Path("Z:/SteamLibrary/steamapps/common/ProjectZomboid/media"))
    parser.add_argument("--write", action="store_true")
    options = parser.parse_args()
    source, count, size, motions = generate(options.media)
    if options.write:
        OUTPUT.write_text(source, encoding="utf-8")
    else:
        assert OUTPUT.read_text(encoding="utf-8") == source, "Generated manifest differs; inspect target assets before regenerating"
    print(f"PASS: {count} stock asset fingerprints, {size} bytes, {motions} native motion/duration checks")

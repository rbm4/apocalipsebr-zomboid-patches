-- Zomboid/db/<serverName>.db account, access-control and support schema.
-- Match V1's unquoted identifiers and PostgreSQL-generated integer IDs.
-- Identity sequences replace SQLite's internal sqlite_sequence table.
CREATE TABLE allowedsteamid (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    steamid TEXT NOT NULL
);

CREATE TABLE bannedid (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    steamid TEXT NOT NULL,
    reason TEXT
);

CREATE TABLE bannedip (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip TEXT NOT NULL,
    username TEXT,
    reason TEXT
);

CREATE TABLE capabilities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    role INTEGER
);

CREATE TABLE defaultRoles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    role INTEGER
);

CREATE TABLE role (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    colorR REAL NOT NULL,
    colorG REAL NOT NULL,
    colorB REAL NOT NULL,
    readonly BOOLEAN DEFAULT false,
    position INTEGER NOT NULL DEFAULT -1
);

CREATE TABLE tickets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message TEXT NOT NULL,
    author TEXT NOT NULL,
    answeredID INTEGER,
    viewed BOOLEAN DEFAULT false
);

CREATE TABLE userlog (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT,
    type TEXT,
    text TEXT,
    issuedBy TEXT,
    amount INTEGER,
    lastUpdate TEXT
);

CREATE TABLE whitelist (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    world TEXT DEFAULT '',
    username TEXT,
    password TEXT,
    lastConnection TEXT,
    role INTEGER NOT NULL,
    authType INTEGER DEFAULT 1,
    googleKey TEXT,
    steamid TEXT,
    ownerid TEXT,
    displayName TEXT
);

CREATE INDEX idx_bannedip_ip ON bannedip (ip);
CREATE INDEX idx_bannedip_username ON bannedip (username);
CREATE INDEX idx_capabilities_role ON capabilities (role);
CREATE INDEX idx_defaultRoles_name ON defaultRoles (name);
CREATE UNIQUE INDEX username ON whitelist (username);
-- Primary keys already index whitelist.id and role.id.
